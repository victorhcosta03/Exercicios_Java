public class TestaTiposPrimitivos {
	
	public static void main (String[] args) {
		byte testeByte = 127;
		short testeShort = 32767;
		int testeInt = 2147483647;
		long testeLong = 922337203685475807L;
		float testeFloat = 3.4189450175641480615024984062548F;
		double testeDouble = 1.7019568196839567941760598341561;
		char testeChar = 'V';
		boolean testeBoolean = true;
		
		System.out.println("Variavel byte: " + testeByte);
		System.out.println("Variavel short: " + testeShort);
		System.out.println("Variavel int: " + testeInt);
		System.out.println("Variavel long: " + testeLong);
		System.out.println("Variavel float: " + testeFloat);
		System.out.println("Variavel double: " + testeDouble);
		System.out.println("Variavel char: " + testeChar);
		System.out.println("Variavel boolean: " + testeBoolean);
		
	}
}

